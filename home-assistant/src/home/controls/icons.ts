/** Maps an `mdi:*` name to a bundled SVG path, or `undefined` if not in the static table. */
export function resolveIconPath(iconName: string | undefined): string | undefined {
  if (!iconName) return undefined
  return MDI_BY_NAME[iconName]
}

/** Resolves an entity icon path: live HA icons first, then offline component icons, then fallback. */
export function resolveEntityIcon(
  entity: HassEntity,
  formatters: EntityFormatters,
  fallbackPath: string = DEFAULT_DOMAIN_ICON,
  state?: string,
): string {
  const liveName = formatters.resolveEntityIconName(entity, state)
  const livePath = resolveIconPath(liveName)
  if (livePath) return livePath

  const domain = domainOf(entity.entity_id)
  const dc = entity.attributes.device_class
  const compareState = state ?? entity.state
  const compDomain = ENTITY_COMPONENT_ICONS[domain]
  if (compDomain) {
    const entry = (dc ? compDomain[dc] : undefined) ?? compDomain._
    const fallbackName = (compareState ? entry?.state?.[compareState] : undefined) ?? entry?.default
    const path = resolveIconPath(fallbackName)
    if (path) return path
  }

  return fallbackPath
}

/** Resolves an attribute value icon path: live HA icons first, then offline component icons, then fallback. */
export function resolveAttributeIcon(
  entity: HassEntity,
  attribute: string,
  value: string | undefined,
  formatters: EntityFormatters,
  fallbackPath: string,
): string {
  const liveName = formatters.resolveAttributeIconName(entity, attribute, value)
  const livePath = resolveIconPath(liveName)
  if (livePath) return livePath

  const domain = domainOf(entity.entity_id)
  const dc = entity.attributes.device_class
  const rawVal =
    value ?? (entity.attributes[attribute] != null ? String(entity.attributes[attribute]) : undefined)
  const compDomain = ENTITY_COMPONENT_ICONS[domain]
  if (compDomain) {
    const entry = (dc ? compDomain[dc] : undefined) ?? compDomain._
    const attrIcons = entry?.state_attributes?.[attribute]
    if (attrIcons) {
      const iconName = (rawVal !== undefined ? attrIcons.state?.[rawVal] : undefined) ?? attrIcons.default
      const path = resolveIconPath(iconName)
      if (path) return path
    }
  }

  return fallbackPath
}
